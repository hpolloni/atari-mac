#!/usr/bin/env bash
# Generates docs/spec/requirements/INDEX.md from the requirement files.
#
# Usage:
#   scripts/req-index.sh           write the index
#   scripts/req-index.sh --check   exit with status 1 if the index is not up to date
set -euo pipefail

cd "$(dirname "$0")/.."

readonly dir=docs/spec/requirements
readonly index=$dir/INDEX.md

generate() {
    echo "# Requirement index"
    echo
    echo "Generated by \`scripts/req-index.sh\`. Do not edit."
    echo
    echo "| ID | Title | Status | Priority | Area | Verification |"
    echo "| --- | --- | --- | --- | --- | --- |"
    for file in "$dir"/REQ-*.md; do
        awk -v file="$(basename "$file")" '
            NR == 1 {
                sub(/^# /, "")
                id = $0; sub(/:.*/, "", id)
                title = $0; sub(/^[^:]*: /, "", title)
            }
            /^\| Status \|/       { split($0, f, "|"); status = f[3] }
            /^\| Priority \|/     { split($0, f, "|"); priority = f[3] }
            /^\| Area \|/         { split($0, f, "|"); area = f[3] }
            /^\| Verification \|/ { split($0, f, "|"); verification = f[3] }
            END {
                gsub(/^ +| +$/, "", status); gsub(/^ +| +$/, "", priority)
                gsub(/^ +| +$/, "", area); gsub(/^ +| +$/, "", verification)
                printf "| [%s](%s) | %s | %s | %s | %s | %s |\n", id, file, title, status, priority, area, verification
            }' "$file"
    done
}

if [[ "${1:-}" == "--check" ]]; then
    if ! diff -u "$index" <(generate); then
        echo "$index is out of date. Run scripts/req-index.sh." >&2
        exit 1
    fi
else
    generate >"$index"
fi
